mod tests {
    use super::*;

    #[test]
    fn test_constants_defined() {
        assert_eq!(RECURSION_DEPTH_LIMIT, 256);
        assert_eq!(MAX_FUNCTION_FILE_LENGTH, 50);
        assert_eq!(INST_ONLY_FORCED_FUNCTIONS, 0);
        assert_eq!(INST_HASH_INDEX, 9);
        assert_eq!(SHARED_LIBRARY_CACHE_INDEX, 30);
        assert_eq!(TMP_VARIABLE_INDEX, 4);
        assert_eq!(ITERATOR_INDEX, 5);
        assert_eq!(CLASS_EXTENDS_INDEX, 25);
    }

    #[test]
    fn test_global_roots_start_at_9() {
        assert!(INST_HASH_INDEX >= 9);
        assert!(SHARED_LIBRARY_CACHE_INDEX >= 9);
    }

    #[test]
    fn test_tick_indexes_range() {
        assert!(TMP_VARIABLE_INDEX >= 0);
        assert!(CLASS_EXTENDS_INDEX <= 25);
    }
}
